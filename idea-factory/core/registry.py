"""License registry. Every data source a lane relies on must be registered here
(core/sources.json for shared sources, lanes/<slug>/sources.json for lane-specific
ones) BEFORE a lane fetches from it. The fetcher refuses unregistered sources and
sources whose commercial_ok flag is false (unless explicitly inspecting for G0).

Fields per source:
  id, name, owner, base_url, terms_url, license, commercial_ok (true|false|"unknown"),
  attribution (text required by the license, or ""), update_frequency, rate_limit,
  key_env (env var holding an API key, or ""), key_param / key_header (how to send it),
  cache_ttl_s, daily_budget, min_interval_s, notes, used_by (list of lane slugs)
"""
import json
import sys
from datetime import date
from . import ROOT, LANES, OPS

CORE_FILE = ROOT / "core" / "sources.json"


class UnregisteredSource(Exception):
    pass


class NonCommercialSource(Exception):
    pass


def _load_file(p):
    if not p.exists():
        return {}
    with open(p, encoding="utf-8") as f:
        data = json.load(f)
    return {s["id"]: s for s in data.get("sources", [])}


def load():
    """Merged registry: core first, then every lane's sources.json (lane wins)."""
    reg = _load_file(CORE_FILE)
    if LANES.exists():
        for lane_dir in sorted(LANES.iterdir()):
            f = lane_dir / "sources.json"
            if f.exists():
                for sid, s in _load_file(f).items():
                    s.setdefault("used_by", [])
                    if lane_dir.name not in s["used_by"]:
                        s["used_by"].append(lane_dir.name)
                    reg[sid] = {**reg.get(sid, {}), **s}
    return reg


def get(source_id):
    reg = load()
    if source_id not in reg:
        raise UnregisteredSource(
            f"Source '{source_id}' is not in core/sources.json or any lanes/*/sources.json. "
            "Register it (license, terms URL, update frequency) before fetching.")
    return reg[source_id]


def check_commercial(source_id, allow_noncommercial=False):
    s = get(source_id)
    ok = s.get("commercial_ok", "unknown")
    if ok is False and not allow_noncommercial:
        raise NonCommercialSource(
            f"Source '{source_id}' license does not allow commercial use ({s.get('license')}). "
            "Lane must be KILLED or flagged; pass allow_noncommercial=True only to inspect for G0.")
    return ok


def render_markdown():
    reg = load()
    lines = [
        "# Data sources and licenses",
        "",
        f"_Generated by `python -m core.board` on {date.today().isoformat()}. Edit `core/sources.json` "
        "or `lanes/<slug>/sources.json`, not this file._",
        "",
        "Rule: a lane may not rely on a source until it is listed here with license and terms. "
        "`commercial_ok = false` means the lane is killed or flagged.",
        "",
        "| Source | Owner | License | Commercial OK | Updates | Rate limit / budget | Key | Used by | Terms |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for sid, s in sorted(reg.items()):
        ok = s.get("commercial_ok", "unknown")
        ok_txt = {True: "yes", False: "**NO**"}.get(ok, "unknown")
        key = s.get("key_env") or "none"
        rl = f"{s.get('rate_limit','?')} / {s.get('daily_budget','?')} per day"
        lines.append(
            f"| `{sid}` {s.get('name','')} | {s.get('owner','')} | {s.get('license','?')} | {ok_txt} | "
            f"{s.get('update_frequency','?')} | {rl} | {key} | {', '.join(s.get('used_by', []))} | "
            f"[terms]({s.get('terms_url','')}) |")
    lines.append("")
    lines.append("## Notes per source")
    lines.append("")
    for sid, s in sorted(reg.items()):
        if s.get("notes") or s.get("attribution"):
            lines.append(f"- **{sid}**: {s.get('notes','')}" +
                         (f" Attribution: _{s['attribution']}_" if s.get("attribution") else ""))
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    if len(sys.argv) > 1 and sys.argv[1] == "render":
        OPS.mkdir(exist_ok=True)
        (OPS / "DATA_SOURCES.md").write_text(render_markdown(), encoding="utf-8")
        print("wrote ops/DATA_SOURCES.md")
    else:
        for sid, s in load().items():
            print(f"{sid:28s} commercial_ok={s.get('commercial_ok')}  {s.get('license')}")
